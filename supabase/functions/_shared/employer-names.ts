//
// THE DATABASE IS THE WRITER. public.company_name_overrides is applied to every
// job_board_postings write by trg_company_name_override (an exact full-token key
// first, then a Workday tenant's first token segment), and each migration that
// adds a row backfills the stored rows. This module MIRRORS that table for the
// readers that render a name the database did not rewrite: the prerender bake
// (scripts/prerender-seo.mjs bundles it like the other shared data modules) and
// the React app (src imports supabase/functions/_shared directly). Pure: no I/O,
// no Deno or browser API.
//
// One function for every renderer: employerDisplayName(token, stored). The
// mirror test (src/test/an-employer-named-by-its-system-code-gets-the-name-it-uses.test.ts)
// replays every migration's writes to company_name_overrides and fails when this
// map and the table differ, so a row added in SQL alone, or here alone, is red.
//
// A name is added only with the employer's own words for itself (its career
// site's sidebar, a posting's hiringOrganization, its tenant path); the evidence
// for each row of a batch rides beside it in the migration that adds it. Never a
// guess: a tenant whose words were not read keeps its stored name.

