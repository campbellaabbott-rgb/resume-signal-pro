/**
 * The override for a board token, by the trigger's own precedence: the exact
 * full token (only a token carrying a "~"; a bare key is a Workday tenant slug,
 * never a greenhouse board that happens to share it), then (Workday only, a
 * token carrying "~wd") its tenant slug.
 */
export function employerNameOverride(token: string | null | undefined): string | null {
  const t = String(token ?? "").trim();
  if (!t) return null;
  const exact = t.includes("~") ? EMPLOYER_NAME_OVERRIDES.get(t) : undefined;
  if (exact !== undefined) return exact;
  if (t.includes("~wd")) {
    const slug = EMPLOYER_NAME_OVERRIDES.get(t.split("~")[0]);
    if (slug !== undefined) return slug;
  }
  return null;
}

/** The name to render for a board: its override, else the name stored with it. */
export function employerDisplayName(token: string | null | undefined, stored: string | null | undefined): string {
  return employerNameOverride(token) ?? String(stored ?? "").trim();
}

/**
 * True when the name to render is still the board's system code: it folds
 * (letters and digits, any case) to the token's first segment and no override
 * names the board. "Ms" for ms~wd5~external, "Rmit" for rmit~wd3~RMIT_Careers.
 * A real one-word name ("Target" for target~wd5~targetcareers) is code-shaped
 * by this test too, so a guard built on it needs an allowlist of real names.
 */
export function isSystemCodeName(token: string | null | undefined, stored: string | null | undefined): boolean {
  const t = String(token ?? "").trim();
  if (!t || employerNameOverride(t) !== null) return false;
  const fold = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
  const name = fold(String(stored ?? ""));
  return name !== "" && name === fold(t.split("~")[0]);
}

/**
 * Feeds that carry many employers under one token, by the name the feed as a
 * whole goes by. Each posting keeps its own employer (a USAJOBS row names its
 * agency); only a surface that names the whole board uses this. The facet entry
 * refresh_job_board_facets writes (20261009100200) carries the same words, and a
 * test holds the two equal.
 */
export const MULTI_EMPLOYER_BOARD_NAMES: ReadonlyMap<string, string> = new Map([
  ["usajobs", "U.S. federal agencies (USAJOBS)"],
]);

/**
 * The name for a whole board (a company lander's H1 and title, a facet chip):
 * a multi-employer feed's own name, else employerDisplayName. A posting card
 * names its own employer with employerDisplayName, never this.
 */
export function boardDisplayName(token: string | null | undefined, stored: string | null | undefined): string {
  return MULTI_EMPLOYER_BOARD_NAMES.get(String(token ?? "").trim()) ?? employerDisplayName(token, stored);
}
