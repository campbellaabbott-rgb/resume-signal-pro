/**
 * THE REPORT MAIL AND THE FIX-PLAN SEQUENCE IN THE READER'S LANGUAGE (S13-102).
 *
 * The report mail is written in the language of the page that asked for it
 * (body.language, then the browser's Accept-Language), and the four fix-plan
 * mails in the language of the page whose button started them, the same way.
 * Anything unknown is English. The sentences the scanner sealed (issues, fix
 * steps, occupation) stay in the language the scan wrote them in, which is the
 * résumé's: only our own words around them change.
 *
 * Every line that goes in the mails' HTML is HTML-safe text written here; a
 * value put into one arrives already escaped. The subjects are plain text.
 * Import-free apart from the shared language rule, so the Node tests import it.
 */
import { checkoutLanguageOf, type CheckoutLanguage } from "../_shared/checkout-policy.ts";

export type MailLanguage = CheckoutLanguage;

/** The page's language, else the browser's first preference we carry, else English. */
export function mailLanguageOf(body: unknown, acceptLanguage: string | null | undefined): MailLanguage {
  const fromBody = checkoutLanguageOf(body);
  if (fromBody) return fromBody;
  for (const part of String(acceptLanguage ?? "").split(",").slice(0, 6)) {
    const tag = part.split(";")[0].trim();
    const lang = tag ? checkoutLanguageOf({ language: tag }) : null;
    if (lang) return lang;
  }
  return "en";
}

/** The Intl locale a language's dates are written in. Tagalog is Intl's Filipino. */
const DATE_LOCALE: Record<MailLanguage, string> = {
  en: "en-US", "en-GB": "en-GB", de: "de-DE", es: "es-ES", fr: "fr-FR", hi: "hi-IN", nl: "nl-NL", pt: "pt-BR", tl: "fil-PH",
};

/** Today the way this reader writes a date. */
export function reportDate(lang: MailLanguage, now: Date = new Date()): string {
  return now.toLocaleDateString(DATE_LOCALE[lang]);
}

