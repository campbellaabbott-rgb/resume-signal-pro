/**
 * Employer-level readers only the lander asks: the lander of a shared token
 * must ask none of them about it. (get_company_fill_curve and
 * get_company_growth are also asked in batches for every card on the page, a
 * per-board badge this change does not touch, so they are not judged here.)
 */
const EMPLOYER_LEVEL = [
  "get_company_financials", "get_similar_companies", "get_company_claim_status", "get_employer_layoff_filings_all", "get_company_hiring_health",
  // The lander's perks block (phase 2) and its filed-wage line (the LCA line
  // that replaced DeclaredWagesCard): both describe one employer.
  "get_employer_perks", "get_employer_lca_wages",
];

function mount(token: string, jobs: ReturnType<typeof job>[]) {
  const path = `/jobs/company/${token}`;
  window.history.replaceState({}, "", path);
  rpc.mockImplementation(async (fn: string, a?: { p_tokens?: string[] }) => {
    if (fn === "get_company_intel") return { data: INTEL, error: null };
    if (fn === "get_company_financials") return { data: { ticker: "CLRX", exchange: "NYSE", sec_name: "Clear Secure", cik: 1, currency: "USD", series: [{ fy: 2025, revenue: 770000000, net_income: 1 }] }, error: null };
    if (fn === "get_company_fill_curve") return { data: (a?.p_tokens ?? []).map(CURVE), error: null };
    if (fn === "get_similar_companies") return { data: [{ company: "Peer Co", company_token: "peerco", open_roles: 9, category: "engineering" }], error: null };
    if (fn === "get_employer_layoff_filings_all") return { data: [FILING], error: null };
    if (fn === "get_employer_lca_wages") return { data: (a?.p_tokens ?? []).map(LCA), error: null };
    return { data: [], error: null };
  });
  invoke.mockImplementation(async (fn: string, a: { body?: Record<string, unknown> } | undefined) => {
    const b = a?.body ?? {};
    if (fn === "job-fit") return { data: { terms: [] }, error: null };
    if (fn === "job-board" && b.action === "detail") return { data: { job: jobs.find((j) => j.id === b.id) ?? jobs[0], description: "A role." } };
    if (fn === "job-board" && b.action === "facets") return { data: { categories: {}, refreshedAt: ago(0), sources: {}, sourcesAt: ago(0) }, error: null };
    if (fn === "job-board" && b.action === "list") {
      if (b.facetCounts) return { data: { categories: {} } };
      if (b.countOnly) return { data: { total: jobs.length } };
      return { data: { jobs, total: jobs.length, totalAllCompanies: jobs.length, companies: [{ token, name: jobs[0].company, open: jobs.length }], companiesCount: 1, categories: {}, failedSources: [], failedCount: 0, refreshedAt: null, hasMore: false } };
    }
    return { data: {} };
  });
  return render(
    <MemoryRouter initialEntries={[path]}>
      <Routes><Route path="/jobs/company/:companyToken" element={<Jobs />} /></Routes>
    </MemoryRouter>,
  );
}
const text = () => document.body.textContent ?? "";
const askedAbout = (token: string) => rpc.mock.calls
  .filter(([fn, a]) => EMPLOYER_LEVEL.includes(fn as string) && (a?.p_token === token || (Array.isArray(a?.p_tokens) && a.p_tokens.length === 1 && a.p_tokens[0] === token)))
  .map(([fn]) => fn as string);

describe("the list of shared tokens is the catalogue's", () => {
  it("every token two hiring systems carry, and only those, with each board's catalogue name", () => {
    const by = new Map<string, Map<string, string>>();
    for (const e of CATALOG) {
      const m = by.get(e.token) ?? new Map<string, string>();
      if (!m.has(e.source)) m.set(e.source, e.name);
      by.set(e.token, m);
    }
    const want = [...by].filter(([, m]) => m.size > 1).map(([t, m]) => [t, [...m].sort(([a], [b]) => (a < b ? -1 : 1))] as const)
      .sort(([a], [b]) => (a < b ? -1 : 1));
    const have = BOARD_COLLISION_ROWS.map(([t, boards]) => [t, boards.map(([s, n]) => [s, n] as const)] as const);
    expect(have.length, "the catalogue held 139 shared tokens on 2026-10-11").toBeGreaterThan(100);
    expect(JSON.stringify(have), "src/lib/board-collisions.ts has drifted from the catalogue: run npx tsx scripts/board-collisions.ts").toBe(JSON.stringify(want));
  });

  it("reads a token, never an inherited key", () => {
    expect(collidedBoards("clear")?.map((b) => b.source)).toEqual(["bamboohr", "greenhouse"]);
    expect(isCollidedToken("constructor")).toBe(false);
    expect(isCollidedToken("blackstone"), "a plain slug beside a Workday tenant is two tokens, not a shared one").toBe(false);
    expect(isCollidedToken(undefined)).toBe(false);
  });
});

describe("the lander of a shared token", () => {
  beforeEach(() => {
    try { sessionStorage.clear(); localStorage.clear(); } catch { /* blocked */ }
    invoke.mockReset(); rpc.mockReset();
  });

  it("positive control: an ordinary employer's page renders intel, SEC figures and Hiring Health from the same mocks", async () => {
    mount("jnj", [job("workday", "jnj", "Johnson & Johnson", 1)]);
    await waitFor(() => expect(text()).toContain("Hiring Health"), SLOW);
    await waitFor(() => expect(text()).toContain("123,456"), SLOW);
    expect(text()).not.toContain("hiring systems carry a board with this name");
    await waitFor(() => expect(askedAbout("jnj")).toContain("get_company_financials"), SLOW);
    // The same mounts ask the perks reader and the filed-wage reader, so their
    // absence on a shared token below is the gate, not a mount nobody makes.
    await waitFor(() => expect(askedAbout("jnj")).toContain("get_employer_perks"), SLOW);
    await waitFor(() => expect(askedAbout("jnj")).toContain("get_employer_lca_wages"), SLOW);
  });

  it("names each board with its hiring system and open roles, and prints no employer-level fact", async () => {
    mount("clear", [job("greenhouse", "clear", "CLEAR - Corporate", 1), job("bamboohr", "clear", "Clear", 2)]);
    await waitFor(() => expect(text()).toContain("2 hiring systems carry a board with this name"), SLOW);
    expect(text()).toContain("Clear on BambooHR");
    expect(text()).toContain("CLEAR - Corporate on Greenhouse");
    await waitFor(() => expect(text()).toContain("open roles now: 3"), SLOW);
    expect(text()).toContain("open roles now: 2");
    // The roles themselves are still listed.
    await waitFor(() => expect(text()).toContain("Platform Engineer 1"), SLOW);
    expect(text()).toContain("Platform Engineer 2");
    // ...and nothing that would describe two companies as one.
    const t = text();
    expect(t, "the intel strip's salary median").not.toContain("123,456");
    expect(t, "the intel strip's headcount").not.toContain("4,321");
    expect(t, "the Hiring Health card").not.toContain("Hiring Health");
    expect(t, "the SEC card").not.toContain("CLRX");
    expect(t, "the similar employers list").not.toContain("Peer Co");
    expect(t, "the filings on record").not.toContain("Clear Secure");
    expect(askedAbout("clear"), "an employer-level reader was asked about the shared token").toEqual([]);
  });
});

describe("the cards and the detail pane of a shared token", () => {
  beforeEach(() => {
    try { sessionStorage.clear(); localStorage.clear(); } catch { /* blocked */ }
    invoke.mockReset(); rpc.mockReset();
  });
  const batchAsked = (fn: string, token: string) => rpc.mock.calls
    .some(([f, a]) => f === fn && Array.isArray(a?.p_tokens) && (a.p_tokens as string[]).includes(token));
  const STAY_OFF = /\bwatched [\d,]+ of its roles come off the board\b/;
  const titles = () => Array.from(document.querySelectorAll<HTMLElement>("[title]")).map((e) => e.getAttribute("title") ?? "");
  const firstCard = () => document.querySelector<HTMLElement>("[data-job-id]")!;
  const openDetail = async () => {
    fireEvent.click(firstCard());
    await waitFor(() => expect(text()).toMatch(/What the data says|The data says/), SLOW);
  };

  it("positive control: an ordinary employer's card and detail pane carry its record and its filed wages", async () => {
    mount("jnj", [job("workday", "jnj", "Johnson & Johnson", 1)]);
    await waitFor(() => expect(text()).toContain("Platform Engineer 1"), SLOW);
    await waitFor(() => expect(batchAsked("get_company_fill_curve", "jnj")).toBe(true), SLOW);
    await waitFor(() => expect(firstCard().textContent).toContain("Actively hiring"), SLOW);
    await openDetail();
    await waitFor(() => expect(text()).toContain("Filed H-1B wages"), SLOW);
    expect(text()).toContain("we watched 9 of its roles come off the board and stay off");
  });

  it("asks no per-board record about it, and its cards and detail pane print no record and no filed wages", async () => {
    mount("clear", [job("greenhouse", "clear", "CLEAR - Corporate", 1), job("bamboohr", "clear", "Clear", 2)]);
    await waitFor(() => expect(text()).toContain("2 hiring systems carry a board with this name"), SLOW);
    await waitFor(() => expect(text()).toContain("Platform Engineer 1"), SLOW);
    // Give the batches a chance to fire: they fire on the same render as the cards.
    await new Promise((r) => setTimeout(r, 100));
    expect(batchAsked("get_company_fill_curve", "clear"), "the fill curve was asked about a shared token").toBe(false);
    expect(batchAsked("get_company_growth", "clear"), "the growth row was asked about a shared token").toBe(false);
    for (const c of Array.from(document.querySelectorAll<HTMLElement>("[data-job-id]"))) {
      expect(c.textContent, "a card on a shared token carried a hiring verdict").not.toMatch(/Actively hiring|Fills fast|No closure record|Closure record withheld/);
    }
    expect(titles().filter((s) => STAY_OFF.test(s))).toEqual([]);
    await openDetail();
    await new Promise((r) => setTimeout(r, 100));
    expect(text(), "the detail pane printed a pooled closure count").not.toMatch(STAY_OFF);
    expect(text(), "the detail pane printed the token's H-1B filings").not.toContain("Filed H-1B wages");
    expect(rpc.mock.calls.some(([f, a]) => f === "get_employer_lca_wages" && (a?.p_tokens as string[] | undefined)?.includes("clear")), "the filed-wage reader was asked about a shared token").toBe(false);
  });
});

describe("the browser's employer cache", () => {
  it("answers a shared token with no facts and asks no reader", async () => {
    rpc.mockReset();
    rpc.mockImplementation(async () => ({ data: INTEL }));
    expect(await getEmployerCtx("clear", "greenhouse")).toEqual({});
    expect(rpc).not.toHaveBeenCalled();
    await getEmployerCtx("jnj", "workday");
    expect(rpc).toHaveBeenCalled();
  });
});
