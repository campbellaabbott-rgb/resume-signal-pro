// A BOARD NAME TWO EMPLOYERS SHARE SHOWS NO EMPLOYER FACTS (company profiles,
// phase 0, plan 2026-10-11 section 2).
//
// 139 catalogue tokens are carried by two hiring systems at once, and nothing
// we hold says whether the two boards are one employer: /jobs/company/clear is
// Clear on BambooHR and CLEAR - Corporate on Greenhouse. Every per-employer
// reader keys on the token, so that page printed one salary median, one
// headcount, one Hiring Health record, one filings list and one similar list
// over two companies. The page now reads the catalogue (src/lib/
// board-collisions.ts, generated by scripts/board-collisions.ts) and shows only
// the per-vendor split with each board's open roles.
//
// 1. The generated list is the catalogue's, recomputed here through the test
//    catalogue reader (not the generator's own import of sources.ts).
// 2. The lander of a shared token renders the split and asks for no
//    employer-level reader; a positive control shows the same mocks render
//    every block on an ordinary employer.
// 3. The browser's employer cache answers a shared token with nothing.
